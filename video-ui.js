"use strict";
/* Video course — "🎬 קורס וידאו": course list → player. One video per guided level (ported from automata-quiz).
   Data: window.VIDEO_COURSE from videos.js (generated by tools/video/build_manifest.py — do not hand-edit it).
     {courses:[{id, title, icon, videos:[{id, level, title, minutes?, youtube?, bonus?}]}]}
     `level` is the guided level id inside course `id` (window.COURSES[id].levels[].id).
   Player: a YouTube id → youtube-nocookie embed; otherwise the local MP4 (videos/out/<ID>/<ID>.mp4, present only
   when the owner runs the site from a checkout with rendered videos); if that fails, a friendly "not uploaded yet" note.
   Watched marks live in localStorage seq_video_v1 = {watched:{<ID>: timestamp}}, apart from the bank stats.
   Loaded before course-ui.js: it exposes window.VIDEO_UI.lessonButtons(levelId, courseId) for the guided lesson
   screen; jumps to a guided level go through the guided-course UI (window.COURSE_UI or window.COURSE), looked up at click time. */
(function(){
  const DATA = window.VIDEO_COURSE && Array.isArray(window.VIDEO_COURSE.courses) ? window.VIDEO_COURSE : { courses: [] };
  const screen = document.getElementById("screen-video");
  const ALL = [];                                   // flat, in course order
  DATA.courses.forEach(c => (c.videos || []).forEach(v => ALL.push(Object.assign({ course: c }, v))));
  const byId = id => ALL.find(v => v.id === id);
  const KEY = "seq_video_v1";
  const q = s => document.querySelector(s);
  const esc = s => String(s == null ? "" : s).replace(/[&<>"]/g, m => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[m]));
  const BIDI = window.bidiHtml || (window.Bidi && window.Bidi.render);
  const text = s => BIDI ? BIDI(esc(s)) : esc(s);
  const APP = window.CC_APP || {};
  const showScreen = id => {
    if (typeof APP.show === "function") APP.show(id);
    else if (typeof show === "function") show(id);
    else { document.querySelectorAll(".screen").forEach(s => s.classList.add("hidden")); document.getElementById(id).classList.remove("hidden"); }
  };
  const goHome = () => { if (typeof APP.quit === "function") APP.quit(); else if (typeof quit === "function") quit(); };
  // the guided-course UI: window.COURSE_UI (course-factory apps) or window.COURSE (mcq apps)
  const guided = () => window.COURSE_UI || (window.COURSE && typeof window.COURSE.openLesson === "function" ? window.COURSE : null);

  if (!screen || !ALL.length){
    document.querySelectorAll(".vid-entry").forEach(el => el.style.display = "none");
    window.VIDEO_UI = { lessonButtons: () => "" };
    return;
  }

  /* ---------- progress ---------- */
  function load(){
    try { const p = JSON.parse(localStorage.getItem(KEY)); if (p && p.watched && typeof p.watched === "object") return p; } catch(e){}
    return { watched: {} };
  }
  let prog = load();
  function save(){ try { localStorage.setItem(KEY, JSON.stringify(prog)); } catch(e){} }
  const watched = id => !!prog.watched[id];
  function setWatched(id, on){ if (on) prog.watched[id] = Date.now(); else delete prog.watched[id]; save(); }

  /* ---------- screens ---------- */
  function view(which){
    showScreen("screen-video");
    q("#vidListView").classList.toggle("hidden", which !== "list");
    q("#vidPlayView").classList.toggle("hidden", which !== "play");
  }
  const minTxt = v => v.minutes ? `${v.minutes} דק׳` : "";
  // not on YouTube yet: on the live site there is no local MP4 either, so the list says "soon" (from file:// the
  // owner's rendered videos/out MP4 plays, so no tag there)
  const soon = v => !v.youtube && location.protocol !== "file:";

  function renderList(){
    const nW = ALL.filter(v => watched(v.id)).length;
    q("#vidOverall").innerHTML = `צפית ב-<b>${nW}</b> מתוך <b>${ALL.length}</b> סרטונים` +
      `<div class="progress" style="margin-top:.5rem"><div class="progress-fill" style="width:${nW / ALL.length * 100}%"></div></div>`;
    q("#vidCourses").innerHTML = DATA.courses.filter(c => (c.videos || []).length).map(c => {
      const n = c.videos.filter(v => watched(v.id)).length;
      return `<section class="card vid-course" data-course="${esc(c.id)}">
        <h3 class="vid-course-h"><span>${esc(c.icon || "")} ${text(c.title)}</span><span class="vid-count">${n}/${c.videos.length}</span></h3>
        <div class="vid-list">${c.videos.map(v => `
          <button type="button" class="vid-row${watched(v.id) ? " watched" : ""}${v.bonus ? " bonus" : ""}${soon(v) ? " soon" : ""}" data-vid="${esc(v.id)}">
            <span class="vid-num" dir="ltr">${esc(v.id)}</span>
            <span class="vid-ttl">${text(v.title)}${v.bonus ? ` <span class="vid-tag">בונוס</span>` : ""}${soon(v) ? ` <span class="vid-tag soon">בקרוב</span>` : ""}</span>
            <span class="vid-meta">${minTxt(v)}</span>
            <span class="vid-check" aria-label="${watched(v.id) ? "נצפה" : "עוד לא נצפה"}">${watched(v.id) ? "✓" : "▶"}</span>
          </button>`).join("")}</div></section>`;
    }).join("");
  }
  function openList(){ if(window.navUrl) navUrl({videos:true}); from = null; stopPlayer(); renderList(); view("list"); }

  /* ---------- player ---------- */
  let cur = null, from = null;          // from: {levelId, courseId} when the player was opened from a guided lesson
  function stopPlayer(){ const f = q("#vidFrame"); if (f) f.innerHTML = ""; }
  function notUploaded(){
    return `<div class="vid-missing"><div class="vid-missing-ico">🎬</div><b>הסרטון הזה עוד לא הועלה.</b>` +
      `<span>הוא בדרך. בינתיים אפשר לקרוא את השיעור של השלב ולתרגל אותו.</span></div>`;
  }
  function mountMedia(v){
    const f = q("#vidFrame");
    f.classList.remove("missing");
    const yt = () => {
      f.innerHTML = `<iframe src="https://www.youtube-nocookie.com/embed/${encodeURIComponent(v.youtube)}?rel=0" title="${esc(v.title)}"
        allow="accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture; web-share"
        referrerpolicy="strict-origin-when-cross-origin" allowfullscreen></iframe>`;
    };
    q("#vidYtLink").innerHTML = v.youtube
      ? `<a href="https://www.youtube.com/watch?v=${encodeURIComponent(v.youtube)}" target="_blank" rel="noopener">לצפייה ב-YouTube ↗</a>` : "";
    // from file:// YouTube refuses the embed (no referrer, error 153): there the local MP4 goes first
    if (v.youtube && location.protocol !== "file:"){ yt(); return; }
    f.innerHTML = `<video controls preload="metadata" playsinline src="videos/out/${encodeURIComponent(v.id)}/${encodeURIComponent(v.id)}.mp4"></video>`;
    const el = f.querySelector("video");
    el.addEventListener("error", () => { if (cur !== v) return; if (v.youtube) yt(); else { f.classList.add("missing"); f.innerHTML = notUploaded(); } });
    el.addEventListener("ended", () => { if (cur === v){ setWatched(v.id, true); paintWatch(); } });
  }
  function paintWatch(){
    const b = q("#vidWatchBtn"), on = cur && watched(cur.id);
    b.textContent = on ? "✓ נצפה (ביטול)" : "סימון כנצפה ✓";
    b.classList.toggle("on", !!on);
  }
  const findLevel = (courseId, levelId) => {
    const C = window.COURSES && window.COURSES[courseId];
    return C && Array.isArray(C.levels) ? C.levels.find(L => L.id === levelId) || null : null;
  };
  const levelOf = v => findLevel(v.course.id, v.level);
  function openVideo(id, opts){ if(window.navUrl&&byId(id)) navUrl({video:id});
    const v = byId(id); if (!v) return openList();
    from = opts && opts.fromLevel ? { levelId: opts.fromLevel, courseId: opts.fromCourse || v.course.id } : null;
    cur = v;
    const i = ALL.indexOf(v), prev = ALL[i - 1], next = ALL[i + 1];
    const L = levelOf(v);
    q("#vidHead").innerHTML =
      `<div class="q-head"><span class="chip">${esc(v.course.icon || "")} ${text(v.course.title)}</span>` +
      `<span class="chip soft" dir="ltr">${esc(v.id)}</span>` +
      (v.minutes ? `<span class="chip soft">${minTxt(v)}</span>` : "") +
      (v.bonus ? `<span class="chip soft">בונוס לשלב ${esc(L ? L.order : v.level)}</span>` : "") + `</div>` +
      `<h2 class="vid-title">${text(v.title)}</h2>`;
    mountMedia(v);
    paintWatch();
    const pb = q("#vidPrev"), nb = q("#vidNext");
    pb.disabled = !prev; nb.disabled = !next;
    pb.title = prev ? prev.title : ""; nb.title = next ? next.title : "";
    const lv = q("#vidLevel");
    lv.style.display = L ? "" : "none";       // course-ui.js may load after a ?video= deep link: checked on click
    lv.textContent = v.bonus && L ? `לתרגול בשלב ${L.order} ⟵` : "לתרגול בשלב הזה ⟵";
    q("#vidBack").textContent = from ? "⟵ חזרה לשיעור" : "⟵ לרשימת הסרטונים";
    view("play");
  }
  function openLevel(levelId, courseId){
    const L = findLevel(courseId, levelId), G = guided();
    if (!L || !G){ openList(); return; }
    stopPlayer();
    G.openMap(courseId);
    G.openLesson(L);
  }

  /* ---------- guided lesson hook (course-ui.js) ---------- */
  function lessonButtons(levelId, courseId){
    const vs = ALL.filter(v => v.level === levelId && (!courseId || v.course.id === courseId));
    if (!vs.length) return "";
    const cid = courseId || vs[0].course.id;
    return `<div class="vid-lesson-btns">` + vs.map(v => v.bonus
      ? `<button type="button" class="btn ghost vid-open" data-vid="${esc(v.id)}" data-from="${esc(levelId)}" data-course="${esc(cid)}">▶ סרטון בונוס: ${text(v.title)}</button>`
      : `<button type="button" class="btn primary vid-open" data-vid="${esc(v.id)}" data-from="${esc(levelId)}" data-course="${esc(cid)}">▶ צפו בסרטון של השלב${soon(v) ? " (בקרוב)" : v.minutes ? ` · ${minTxt(v)}` : ""}</button>`
    ).join("") + `</div>`;
  }

  /* ---------- wiring ---------- */
  document.addEventListener("click", e => {
    const row = e.target.closest(".vid-row"); if (row){ openVideo(row.dataset.vid); return; }
    const b = e.target.closest(".vid-open"); if (b){ openVideo(b.dataset.vid, { fromLevel: b.dataset.from, fromCourse: b.dataset.course }); return; }
    if (e.target.closest(".vid-entry")) openList();
  });
  document.querySelectorAll(".vid-entry[role=button]").forEach(el => el.onkeydown = e => {
    if (e.key === "Enter" || e.key === " "){ e.preventDefault(); openList(); }
  });
  q("#vidPrev").onclick = () => { const i = ALL.indexOf(cur); if (ALL[i - 1]) openVideo(ALL[i - 1].id); };
  q("#vidNext").onclick = () => { const i = ALL.indexOf(cur); if (ALL[i + 1]) openVideo(ALL[i + 1].id); };
  q("#vidWatchBtn").onclick = () => { if (cur){ setWatched(cur.id, !watched(cur.id)); paintWatch(); } };
  q("#vidLevel").onclick = () => { if (cur) openLevel(cur.level, cur.course.id); };
  q("#vidBack").onclick = () => { if (from) openLevel(from.levelId, from.courseId); else openList(); };
  q("#vidHomeBtn").onclick = () => { stopPlayer(); goHome(); };
  // leaving the screen by any route (header, brand, learn) stops playback
  if (window.MutationObserver)
    new MutationObserver(() => { if (screen.classList.contains("hidden")) stopPlayer(); })
      .observe(screen, { attributes: true, attributeFilter: ["class"] });
  function paintPromo(){
    const s = q("#vidPromoSub"); if (!s) return;
    if (!s.dataset.base) s.dataset.base = s.textContent;
    const n = ALL.filter(v => watched(v.id)).length;
    s.textContent = n ? `צפית ב-${n} מתוך ${ALL.length} סרטונים. ${n === ALL.length ? "סיימת, כל הכבוד!" : "אפשר להמשיך מאיפה שעצרת."}` : s.dataset.base;
  }
  paintPromo();
  // app.js quit() fires "seq:home" on window whenever the start screen is shown again
  window.addEventListener("seq:home", paintPromo);

  window.VIDEO_UI = { lessonButtons, openList, openVideo, all: ALL, KEY };

  // deep link: ?videos=1 (list) · ?video=<ID> (player)
  try {
    const p = new URLSearchParams(location.search);
    if (p.get("video") && byId(p.get("video"))) openVideo(p.get("video"));
    else if (p.get("videos")) openList();
  } catch(e){}
})();
