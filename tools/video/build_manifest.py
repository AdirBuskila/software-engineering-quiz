# -*- coding: utf-8 -*-
"""Video course manifest:  videos/<course>/<ID>/<ID>.py + videos/out/<ID>/timeline.json + videos/youtube.json
                          ->  videos.js  (window.VIDEO_COURSE, read by video-ui.js)

usage:  PYTHONUTF8=1 python tools/video/build_manifest.py

The title of each video is read from its script's `VIDEO = Video("<ID>", "<course>", "<title>", ...)` line with a
regex (the scripts are not imported: importing runs their simulator asserts and needs the video toolchain).
`minutes` comes from videos/out/<ID>/timeline.json ("total" seconds) when the video has been rendered, else it is
omitted. `youtube` comes from the hand-edited videos/youtube.json ({"F01": "<11-char id>"}); missing -> omitted, and
the player falls back to the local MP4 (videos/out/<ID>/<ID>.mp4), then to a "not uploaded yet" note.
A video <ID> with a lowercase suffix (K06a, K06b) is a bonus video of guided level <ID without suffix> and is listed
right after it.
"""
import json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
VIDEOS = ROOT / "videos"
OUT = ROOT / "videos.js"

sys.path.insert(0, str(VIDEOS))
import app_config  # noqa: E402

COURSES = app_config.COURSES      # same order and names as course-ui.js
DECL = re.compile(r'^VIDEO\s*=\s*Video\(\s*"([^"]+)"\s*,\s*"([^"]+)"\s*,\s*"([^"]+)"', re.M)
ID_RE = re.compile(r"^([A-Z])(\d+)([a-z]?)$")
YT_RE = re.compile(r"^[A-Za-z0-9_-]{11}$")


def sort_key(vid):
    m = ID_RE.match(vid)
    return (int(m.group(2)), m.group(3)) if m else (10 ** 6, vid)


def main():
    errors = []
    yt_path = VIDEOS / "youtube.json"
    youtube = json.loads(yt_path.read_text(encoding="utf-8")) if yt_path.exists() else {}
    if not isinstance(youtube, dict):
        sys.exit("videos/youtube.json must be an object {\"F01\": \"<youtube id>\"}")
    seen = set()
    courses = []
    for cid, title, icon in COURSES:
        vids = []
        for script in sorted((VIDEOS / cid).glob("*/*.py")):
            if script.stem != script.parent.name:
                continue
            m = DECL.search(script.read_text(encoding="utf-8"))
            if not m:
                errors.append(f"{script.relative_to(ROOT)}: no VIDEO = Video(\"ID\", \"course\", \"title\", ...) line")
                continue
            vid, course, vtitle = m.groups()
            if vid != script.stem or course != cid:
                errors.append(f"{script.relative_to(ROOT)}: declares {vid}/{course}, expected {script.stem}/{cid}")
                continue
            if not ID_RE.match(vid):
                errors.append(f"{vid}: unexpected id shape")
                continue
            v = {"id": vid, "level": ID_RE.match(vid).group(1) + ID_RE.match(vid).group(2).zfill(2), "title": vtitle}
            if ID_RE.match(vid).group(3):
                v["bonus"] = True
            tl = VIDEOS / "out" / vid / "timeline.json"
            if tl.exists():
                try:
                    total = float(json.loads(tl.read_text(encoding="utf-8"))["total"])
                    v["minutes"] = max(1, round(total / 60))
                except (ValueError, KeyError, TypeError) as e:
                    errors.append(f"{tl.relative_to(ROOT)}: unreadable total ({e})")
            y = str(youtube.get(vid, "") or "").strip()
            if y:
                if YT_RE.match(y):
                    v["youtube"] = y
                else:
                    errors.append(f"videos/youtube.json: {vid} = {y!r} is not an 11-character YouTube id")
            vids.append(v)
            seen.add(vid)
        vids.sort(key=lambda v: sort_key(v["id"]))
        courses.append({"id": cid, "title": title, "icon": icon, "videos": vids})
    for k in youtube:
        if k not in seen:
            errors.append(f"videos/youtube.json: {k} has no video script")
    if errors:
        print("\n".join("ERROR " + e for e in errors))
        sys.exit(1)
    body = json.dumps({"courses": courses}, ensure_ascii=False, indent=1)
    OUT.write_text(
        "/* GENERATED by tools/video/build_manifest.py from videos/<course>/<ID>/<ID>.py, videos/out/<ID>/timeline.json\n"
        "   and videos/youtube.json. Do not hand-edit: change the sources and rerun the script. */\n"
        f"window.VIDEO_COURSE = {body};\n", encoding="utf-8")
    n = sum(len(c["videos"]) for c in courses)
    nm = sum(1 for c in courses for v in c["videos"] if "minutes" in v)
    ny = sum(1 for c in courses for v in c["videos"] if "youtube" in v)
    print(f"videos.js: {n} videos ({nm} with a duration, {ny} with a YouTube id)")


if __name__ == "__main__":
    main()
